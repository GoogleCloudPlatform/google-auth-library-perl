#!/usr/bin/env perl
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Find     qw(find);
use File::Path     qw(make_path);

my %dist_main_pm = (
    'Protobuf'                => 'Protobuf/lib/Protobuf.pm',
    'Google-Api-Common'       => 'Google-Api-Common/lib/Google/Api/Common.pm',
    'Google-Auth'             => 'Google-Auth/lib/Google/Auth.pm',
    'Google-gRPC'             => 'Google-gRPC/lib/Google/gRPC.pm',
    'Module-Starter-Protobuf' => 'Module-Starter-Protobuf/lib/Module/Starter/Protobuf.pm',
);

my %dist_versions;
for my $dist (keys %dist_main_pm) {
    open my $fh, '<:encoding(UTF-8)', $dist_main_pm{$dist} or die 'Cannot read ' . $dist_main_pm{$dist} . ': ' . $!;
    local $/;
    my $src = <$fh>;
    close $fh;
    if ($src =~ /our\s+\$VERSION\s*=\s*['"]([0-9.]+)['"]/) {
        $dist_versions{$dist} = $1;
    } else {
        die 'Could not detect $VERSION in ' . $dist_main_pm{$dist};
    }
}

my $out_file = $ARGV[0] || 'tmp/audit_pod_quality.out';
my @issues;

for my $dist (sort keys %dist_versions) {
    my $expected_ver = $dist_versions{$dist};
    my @dirs = grep { -d $_ } ($dist . '/lib', $dist . '/bin', $dist . '/pod');
    find(
        sub {
            return unless -f $_ && !-B $_;
            return if $File::Find::name =~ m{/(?:Conformance|Protobuf_test_messages)/};
            return unless /\.(?:pm|pod|pl)\z/ || $File::Find::dir =~ m{/bin\z};

            my $path = $File::Find::name;
            open my $fh, '<:encoding(UTF-8)', $_ or return;
            local $/;
            my $content = <$fh>;
            close $fh;

            my $is_generated = ($content =~ /Generated by protoc-gen-perl-pb|DO NOT EDIT|Automatically generated/i) ? 1 : 0;

            my $pod = '';
            while ($content =~ /^(=\w+.*?^=cut\s*$)/gms) {
                $pod .= $1 . "\n";
            }
            if ($path =~ /\.pod\z/) {
                $pod = $content;
            }

            if ($pod =~ /^=head1\s+VERSION\s+(.*?)(?=^=head1|^=cut|\z)/ms) {
                my $ver_block = $1;
                if ($ver_block =~ /(\d+\.\d+(?:\.\d+)?)/) {
                    my $found_ver = $1;
                    if ($found_ver ne $expected_ver) {
                        push @issues, 'STALE_VERSION: ' . $path . ' (found ' . $found_ver . ', expected ' . $expected_ver . ')';
                    }
                }
            }

            if ($path =~ /\.pm\z/ && $content =~ /^package\s+([A-Za-z0-9_:]+)\s*;/m) {
                my $pkg = $1;
                if ($pod =~ /^=head1\s+NAME\s+(\S+)/ms) {
                    my $pod_name = $1;
                    if ($pod_name ne $pkg) {
                        push @issues, 'WRONG_NAME: ' . $path . ' (POD NAME ' . $pod_name . ' != package ' . $pkg . ')';
                    }
                } else {
                    push @issues, 'NO_POD_NAME: ' . $path . ' (package ' . $pkg . ')';
                }
            }

            if (!$is_generated) {
                my $pod_lines = () = $pod =~ /\S/g ? ($pod =~ /^.*$/mg) : ();
                my $desc = '';
                if ($pod =~ /^=head1\s+DESCRIPTION\s+(.*?)(?=^=head1|^=cut|\z)/ms) {
                    $desc = $1;
                    $desc =~ s/^\s+|\s+$//g;
                }
                my $desc_len = length($desc);
                my $has_methods = ($pod =~ /^=head[12]\s+(?:METHODS|FUNCTIONS|SUBROUTINES|CLASS METHODS|INSTANCE METHODS|OPTIONS|COMMANDS)/m) ? 1 : 0;
                my @pub_subs = ($content =~ /^sub\s+([a-zA-Z][a-zA-Z0-9_]*)\b/mg);
                @pub_subs = grep { !/^(?:BUILD|BUILDARGS|DEMOLISH|CLONE_SKIP|import|new)\z/ } @pub_subs;

                if ($pod_lines < 25 || ($desc_len < 120 && $path !~ /Error\.pm\z/)) {
                    push @issues, 'THIN_POD: ' . $path . ' (pod_lines=' . $pod_lines . ', desc_len=' . $desc_len . ', pub_subs=' . scalar(@pub_subs) . ', has_methods=' . $has_methods . ')';
                } elsif (@pub_subs >= 2 && !$has_methods) {
                    push @issues, 'NO_METHODS_DOC: ' . $path . ' (pod_lines=' . $pod_lines . ', pub_subs=' . scalar(@pub_subs) . ')';
                }
            }
        },
        @dirs
    );
}

make_path(dirname($out_file));
open my $out, '>:encoding(UTF-8)', $out_file or die $!;
for my $i (@issues) {
    print {$out} $i . "\n";
}
close $out;
print 'Total issues: ' . scalar(@issues) . ' (report: ' . $out_file . ")\n";
